export function createCleanProfile(
  studentId: string,
  firstName: string,
  lastName: string,
  faculty: string = 'คณะนิติศาสตร์',
  major: string = 'สาขาวิชานิติศาสตร์'
): StudentProfile {
  const cleanId = studentId.trim();
  const yearPrefix = cleanId.length >= 2 ? cleanId.substring(0, 2) : '67';
  const admissionYear = `25${yearPrefix}`;

  return {
    studentId: cleanId,
    name: `${firstName.trim()} ${lastName.trim()}`,
    email: `${cleanId}@rumail.ru.ac.th`,
    faculty,
    major,
    curriculumYear: '2565',
    admissionYear,
    currentAcademicYear: '2569',
    currentSemester: '1/2569',
    graduationTargetYears: 3,
    targetGradSemester: `2/25${parseInt(yearPrefix, 10) + 3}`,
    totalCreditsRequired: 132,
    avatarUrl: '',
  };
}

